"""Starter catalogue of well-known schemes compiled from public information.
Every record is 'unverified' until an administrator checks it against the official source."""


def L(en, hi="", bn=""):
    return {k: v for k, v in {"en": en, "hi": hi, "bn": bn}.items() if v}


def E(*items):
    return {"en": list(items)}


